//! The real `rag2` binary, end to end: init, offline config management, keys, OpenAPI, then a
//! served instance driven by `status`, `ingest`, `query` and the MCP stdio bridge.

use std::io::Write;
use std::path::Path;
use std::process::{Child, Command, Output, Stdio};
use std::time::Duration;

const READY_TRIES: usize = 300;
const READY_POLL: Duration = Duration::from_millis(50);

fn rag2() -> Command {
    let mut c = Command::new(env!("CARGO_BIN_EXE_rag2"));
    c.env_remove("RAG2_URL")
        .env_remove("RAG2_API_KEY")
        .env_remove("RAG2_CONFIG_DIR")
        .env_remove("RAG2_PROFILE")
        .env_remove("RAG2_ENV");
    c
}

fn ok(o: Output) -> String {
    assert!(
        o.status.success(),
        "exit {:?}\nstdout: {}\nstderr: {}",
        o.status,
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    );
    String::from_utf8_lossy(&o.stdout).into_owned()
}

/// `export NAME=value` lines from `rag2.env`, with `$NAME` references resolved.
fn env_file(p: &Path) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    for l in std::fs::read_to_string(p).expect("env").lines() {
        let Some((k, v)) = l.strip_prefix("export ").and_then(|x| x.split_once('=')) else {
            continue;
        };
        let v = v
            .strip_prefix('$')
            .and_then(|r| out.iter().find(|(n, _)| n == r).map(|(_, x)| x.clone()))
            .unwrap_or_else(|| v.to_string());
        out.push((k.to_string(), v));
    }
    out
}

fn free_port() -> u16 {
    std::net::TcpListener::bind("127.0.0.1:0")
        .expect("bind")
        .local_addr()
        .expect("addr")
        .port()
}

struct Server(Child);

impl Drop for Server {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

#[test]
fn init_config_keys_and_openapi_offline() {
    let dir = tempfile::tempdir().expect("tempdir");
    let d = dir.path();
    ok(rag2()
        .args(["init", "--dir"])
        .arg(d)
        .output()
        .expect("init"));
    assert!(
        !rag2()
            .args(["init", "--dir"])
            .arg(d)
            .output()
            .expect("init")
            .status
            .success(),
        "init refuses to overwrite"
    );
    let yaml = d.join("rag2.yaml");
    ok(rag2()
        .args(["config", "validate"])
        .arg(&yaml)
        .output()
        .expect("validate"));
    let bad = d.join("bad.yaml");
    std::fs::write(
        &bad,
        "api_version: rag2/v1\nmetadata: {name: main}\ndefault_pipeline: nope\n",
    )
    .expect("write");
    assert!(
        !rag2()
            .args(["config", "validate"])
            .arg(&bad)
            .output()
            .expect("v")
            .status
            .success()
    );

    let cfg = |sub: &str| {
        let mut c = rag2();
        c.args(["config", sub, "--config-dir"]).arg(d.join("cfg"));
        c
    };
    let diff = ok(cfg("diff").arg(&yaml).output().expect("diff"));
    assert!(!diff.trim().is_empty());
    ok(cfg("apply")
        .arg(&yaml)
        .args(["--comment", "first"])
        .output()
        .expect("apply"));
    let tuned = d.join("tuned.yaml");
    std::fs::write(
        &tuned,
        std::fs::read_to_string(&yaml)
            .expect("yaml")
            .replace("Starter profile generated by rag2 init", "tuned"),
    )
    .expect("write");
    ok(cfg("apply").arg(&tuned).output().expect("apply"));
    assert!(ok(cfg("export").output().expect("export")).contains("tuned"));
    let history = ok(cfg("history").output().expect("history"));
    assert!(history.contains("first"), "{history}");
    ok(cfg("rollback").output().expect("rollback"));
    assert!(!ok(cfg("export").output().expect("export")).contains("description: tuned"));

    let schema: serde_json::Value = serde_json::from_str(&ok(rag2()
        .args(["config", "schema"])
        .output()
        .expect("schema")))
    .expect("schema json");
    assert!(schema["properties"]["decision_models"].is_object());
    let api: serde_json::Value =
        serde_json::from_str(&ok(rag2().arg("openapi").output().expect("openapi")))
            .expect("openapi json");
    assert!(
        api["openapi"]
            .as_str()
            .is_some_and(|v| v.starts_with("3.1"))
    );
    assert!(
        ok(rag2().args(["key", "api"]).output().expect("key"))
            .trim()
            .len()
            >= 32
    );
    assert_eq!(
        ok(rag2().args(["key", "encryption"]).output().expect("key"))
            .trim()
            .len(),
        64
    );
}

#[test]
fn served_instance_status_ingest_query_and_mcp() {
    let dir = tempfile::tempdir().expect("tempdir");
    let d = dir.path();
    ok(rag2()
        .args(["init", "--dir"])
        .arg(d)
        .output()
        .expect("init"));
    let port = free_port();
    let yaml = d.join("rag2.yaml");
    let mut profile: serde_json::Value =
        serde_norway::from_str(&std::fs::read_to_string(&yaml).expect("yaml")).expect("profile");
    profile["server"]["listen"] = format!("127.0.0.1:{port}").into();
    profile["storage"]["data_dir"] = d.join("data").display().to_string().into();
    std::fs::write(&yaml, serde_norway::to_string(&profile).expect("yaml")).expect("write");
    let env = env_file(&d.join("rag2.env"));
    let url = format!("http://127.0.0.1:{port}");
    let with_env = |mut c: Command| {
        c.envs(env.iter().map(|(k, v)| (k.as_str(), v.as_str())))
            .env("RAG2_URL", &url)
            .env("RAG2_CONFIG_DIR", d.join("cfg"));
        c
    };
    let mut serve = with_env(rag2());
    serve
        .args(["serve", "--file"])
        .arg(&yaml)
        .stdout(Stdio::null())
        .stderr(Stdio::null());
    let _server = Server(serve.spawn().expect("serve"));
    let mut up = false;
    for _ in 0..READY_TRIES {
        let mut c = with_env(rag2());
        if c.arg("status").output().is_ok_and(|o| o.status.success()) {
            up = true;
            break;
        }
        std::thread::sleep(READY_POLL);
    }
    assert!(up, "server never became ready");

    let docs = d.join("docs");
    std::fs::create_dir_all(&docs).expect("docs");
    std::fs::write(
        docs.join("seals.md"),
        "Pump seals are inspected every 500 hours.",
    )
    .expect("doc");
    std::fs::write(
        docs.join("lunch.txt"),
        "The cafeteria serves lunch from twelve.",
    )
    .expect("doc");
    std::fs::write(docs.join("skip.bin"), [0u8, 1, 2]).expect("doc");
    let mut c = with_env(rag2());
    let out = ok(c
        .args(["ingest", "-t", "plant"])
        .arg(&docs)
        .output()
        .expect("ingest"));
    assert!(out.contains('2'), "{out}");

    let mut c = with_env(rag2());
    let out = ok(c
        .args([
            "query",
            "-t",
            "plant",
            "--json",
            "how often are pump seals inspected",
        ])
        .output()
        .expect("query"));
    let r: serde_json::Value = serde_json::from_str(&out).expect("query json");
    assert!(
        r["evidence"][0]["provenance"]["doc_id"]
            .as_str()
            .is_some_and(|id| id.ends_with("seals.md"))
    );
    let mut c = with_env(rag2());
    let out = ok(c
        .args(["query", "-t", "plant", "cafeteria lunch"])
        .output()
        .expect("query"));
    assert!(out.contains("lunch"), "{out}");

    let mut c = with_env(rag2());
    let mut mcp = c
        .arg("mcp")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("mcp");
    mcp.stdin
        .take()
        .expect("stdin")
        .write_all(b"{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"tools/list\"}\n")
        .expect("write");
    let out = ok(mcp.wait_with_output().expect("mcp output"));
    assert!(out.contains("search"), "{out}");
}
