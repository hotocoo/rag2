//! `rag2 init`: a working starter profile plus generated credentials, so a first install is
//! `rag2 init && source rag2.env && rag2 serve --file rag2.yaml`.

use anyhow::{Result, bail};
use rag2_config::schema::{ApiKey, AuthConfig, SecretRef};
use rag2_config::{Profile, validate};
use std::path::Path;

const PROFILE_FILE: &str = "rag2.yaml";
const ENV_FILE: &str = "rag2.env";
const ADMIN_KEY_ENV: &str = "RAG2_ADMIN_KEY";
const ENCRYPTION_KEY_ENV: &str = "RAG2_ENCRYPTION_KEY";

const HEADER: &str = "\
# RAG2 profile. Every field is documented in the JSON Schema: `rag2 config schema`.
# Validate: rag2 config validate rag2.yaml
# Run:      source rag2.env && rag2 serve --file rag2.yaml --watch
# Secrets are referenced (env:NAME or file:/path), never written here.
";

pub fn starter_profile() -> Profile {
    let mut p = Profile::minimal("main");
    p.metadata.description = "Starter profile generated by rag2 init".into();
    p.security.auth = AuthConfig::ApiKeys {
        keys: vec![ApiKey {
            id: "admin".into(),
            secret: SecretRef::Env(ADMIN_KEY_ENV.into()),
            roles: vec!["admin".into()],
            tenants: vec!["*".into()],
        }],
    };
    p.storage.encryption_key = Some(SecretRef::Env(ENCRYPTION_KEY_ENV.into()));
    p
}

pub fn run(dir: &Path, force: bool) -> Result<()> {
    let profile_path = dir.join(PROFILE_FILE);
    let env_path = dir.join(ENV_FILE);
    for p in [&profile_path, &env_path] {
        if p.exists() && !force {
            bail!("{} exists; pass --force to overwrite", p.display());
        }
    }
    let p = starter_profile();
    let errors: Vec<_> = validate(&p)
        .into_iter()
        .filter(|i| i.severity == rag2_config::Severity::Error)
        .collect();
    if !errors.is_empty() {
        bail!("generated profile failed validation: {errors:?}");
    }
    std::fs::create_dir_all(dir)?;
    std::fs::write(
        &profile_path,
        format!("{HEADER}{}", serde_norway::to_string(&p)?),
    )?;
    let env = format!(
        "# Generated by rag2 init. Keep this file secret (chmod 600) or move the values to your secret manager.\nexport {ADMIN_KEY_ENV}={}\nexport {ENCRYPTION_KEY_ENV}={}\nexport RAG2_API_KEY=${ADMIN_KEY_ENV}\n",
        crate::api_key()?,
        crate::encryption_key()?,
    );
    write_private(&env_path, &env)?;
    println!(
        "wrote {} and {}",
        profile_path.display(),
        env_path.display()
    );
    println!(
        "next: source {} && rag2 serve --file {} --watch",
        env_path.display(),
        profile_path.display()
    );
    Ok(())
}

#[cfg(unix)]
fn write_private(path: &Path, text: &str) -> Result<()> {
    use std::io::Write;
    use std::os::unix::fs::OpenOptionsExt;
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(path)?;
    f.write_all(text.as_bytes())?;
    Ok(())
}

#[cfg(not(unix))]
fn write_private(path: &Path, text: &str) -> Result<()> {
    std::fs::write(path, text)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_writes_a_valid_profile_and_refuses_to_overwrite() {
        let dir = tempfile::tempdir().expect("tempdir");
        run(dir.path(), false).expect("init");
        let text = std::fs::read_to_string(dir.path().join(PROFILE_FILE)).expect("read");
        let v = rag2_config::parse_profile_value(&text).expect("parse");
        let p = rag2_config::resolve(&v, None).expect("resolve");
        assert!(
            validate(&p)
                .iter()
                .all(|i| i.severity != rag2_config::Severity::Error)
        );
        assert!(
            !text.contains(&std::fs::read_to_string(dir.path().join(ENV_FILE)).expect("env")[..20])
        );
        assert!(run(dir.path(), false).is_err());
    }
}
